package com.example.payments.repository;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import com.example.payments.TestcontainersConfiguration;
import com.example.payments.model.DeclineReason;
import com.example.payments.model.Money;
import com.example.payments.model.Payment;
import com.example.payments.model.PaymentStatus;
import com.example.payments.model.WebhookEvent;
import jakarta.persistence.EntityManager;
import java.time.Instant;
import java.util.UUID;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.data.jpa.test.autoconfigure.DataJpaTest;
import org.springframework.boot.jdbc.test.autoconfigure.AutoConfigureTestDatabase;
import org.springframework.context.annotation.Import;
import org.springframework.dao.DataIntegrityViolationException;
import org.springframework.orm.ObjectOptimisticLockingFailureException;

/**
 * Runs against a real Postgres (Testcontainers) with the schema generated by Hibernate
 * from the entities, so these tests prove the declared constraints really exist.
 */
@DataJpaTest(properties = "spring.jpa.hibernate.ddl-auto=create-drop")
@AutoConfigureTestDatabase(replace = AutoConfigureTestDatabase.Replace.NONE)
@Import(TestcontainersConfiguration.class)
class PersistenceTest {

    @Autowired
    PaymentRepository payments;
    @Autowired
    WebhookEventRepository events;
    @Autowired
    EntityManager em;

    private Payment newPayment(String key) {
        return Payment.create(key, "a".repeat(64), Money.parse("125.50", "GBP"));
    }

    private void flushAndClear() {
        em.flush();
        em.clear();
    }

    @Test
    void savesAndReloadsAPayment() {
        Payment saved = payments.save(newPayment("key-1"));
        flushAndClear();

        Payment loaded = payments.findById(saved.getId()).orElseThrow();
        assertThat(loaded.getStatus()).isEqualTo(PaymentStatus.PDNG);
        assertThat(loaded.getProviderPaymentId()).isNull();
        assertThat(loaded.money()).isEqualTo(Money.parse("125.50", "GBP"));
        assertThat(loaded.getEndToEndId()).hasSize(32).isEqualTo(saved.getId().toString().replace("-", ""));
        assertThat(loaded.getRequestHash()).isEqualTo("a".repeat(64));
        assertThat(loaded.getCreatedAt()).isNotNull();
        assertThat(loaded.getUpdatedAt()).isNotNull();
    }

    @Test
    void findsByIdempotencyKeyAndEndToEndId() {
        Payment saved = payments.save(newPayment("key-2"));
        flushAndClear();

        assertThat(payments.findByIdempotencyKey("key-2")).isPresent();
        assertThat(payments.findByEndToEndId(saved.getEndToEndId())).isPresent();
        assertThat(payments.findByIdempotencyKey("nope")).isEmpty();
    }

    @Test
    void idempotencyKeyIsUnique() {
        payments.saveAndFlush(newPayment("dup"));
        assertThatThrownBy(() -> payments.saveAndFlush(newPayment("dup")))
                .isInstanceOf(DataIntegrityViolationException.class);
    }

    @Test
    void endToEndIdIsUnique() {
        Payment first = payments.saveAndFlush(newPayment("k-a"));
        assertThatThrownBy(() -> em.createNativeQuery("""
                insert into payment (id, end_to_end_id, idempotency_key, request_hash, amount_minor,
                                     currency, status, version, created_at, updated_at)
                values (?1, ?2, 'k-b', ?3, 100, 'GBP', 'PDNG', 0, now(), now())
                """)
                .setParameter(1, UUID.randomUUID())
                .setParameter(2, first.getEndToEndId())
                .setParameter(3, "b".repeat(64))
                .executeUpdate())
                .hasMessageContaining("end_to_end_id");
    }

    @Test
    void databaseRejectsNonPositiveAmounts() {
        assertThatThrownBy(() -> {
            em.createNativeQuery("""
                    insert into payment (id, end_to_end_id, idempotency_key, request_hash, amount_minor,
                                         currency, status, version, created_at, updated_at)
                    values (?1, ?2, 'k-zero', ?3, 0, 'GBP', 'PDNG', 0, now(), now())
                    """)
                    .setParameter(1, UUID.randomUUID())
                    .setParameter(2, "c".repeat(32))
                    .setParameter(3, "c".repeat(64))
                    .executeUpdate();
        }).hasMessageContaining("check constraint");
    }

    @Test
    void validTransitionIsPersisted() {
        Payment p = payments.saveAndFlush(newPayment("k-t1"));
        assertThat(p.applyStatus(PaymentStatus.RJCT, DeclineReason.AM04)).isTrue();
        flushAndClear();

        Payment loaded = payments.findById(p.getId()).orElseThrow();
        assertThat(loaded.getStatus()).isEqualTo(PaymentStatus.RJCT);
        assertThat(loaded.getStatusReason()).isEqualTo(DeclineReason.AM04);
    }

    @Test
    void lateAcceptAfterCancelIsIgnored() {
        Payment p = newPayment("k-t2");
        p.applyStatus(PaymentStatus.CANC, null);
        assertThat(p.applyStatus(PaymentStatus.ACCP, null)).isFalse();
        assertThat(p.getStatus()).isEqualTo(PaymentStatus.CANC);
    }

    @Test
    void concurrentUpdatesAreDetectedByOptimisticLocking() {
        Payment saved = payments.saveAndFlush(newPayment("k-lock"));
        flushAndClear();

        Payment stale = payments.findById(saved.getId()).orElseThrow();
        em.detach(stale);

        Payment fresh = payments.findById(saved.getId()).orElseThrow();
        fresh.applyStatus(PaymentStatus.ACCP, null);
        flushAndClear();

        stale.applyStatus(PaymentStatus.CANC, null);
        assertThatThrownBy(() -> payments.saveAndFlush(stale))
                .isInstanceOf(ObjectOptimisticLockingFailureException.class);
    }

    @Test
    void webhookEventIdIsUnique() {
        Payment p = payments.saveAndFlush(newPayment("k-wh"));
        Instant now = Instant.now();
        events.saveAndFlush(new WebhookEvent("evt-1", p, PaymentStatus.ACCP, now, now));

        assertThatThrownBy(() -> events.saveAndFlush(new WebhookEvent("evt-1", p, PaymentStatus.ACCP, now, now)))
                .isInstanceOf(DataIntegrityViolationException.class);
    }

    @Test
    void webhookEventMustReferenceAnExistingPayment() {
        assertThatThrownBy(() -> em.createNativeQuery("""
                insert into webhook_event (event_id, payment_id, status, occurred_at, received_at)
                values ('evt-2', ?1, 'ACCP', now(), now())
                """)
                .setParameter(1, UUID.randomUUID())
                .executeUpdate())
                .hasMessageContaining("foreign key");
    }
}
